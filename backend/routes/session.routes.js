const express = require('express');
const router = express.Router();
const { protect } = require('../middleware/auth.middleware');
const { authorise } = require('../middleware/role.middleware');
const { createSlot, getAvailableSlots, bookSlot, getMyHistory, rateSession } = require('../controllers/session.controller');
router.post('/slots',      protect, authorise('teacher'), createSlot);
router.get('/slots',       protect, getAvailableSlots);
router.post('/book/:id',   protect, authorise('student'), bookSlot);
router.get('/history',     protect, getMyHistory);
router.post('/rate/:id',   protect, authorise('student'), rateSession);
module.exports = router;
